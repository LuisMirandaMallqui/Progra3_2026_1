CREATE PROCEDURE INSERTAR_FACULTAD(
    INOUT p_facultad_id BIGINT UNSIGNED, IN p_nombre VARCHAR(100), IN p_activo TINYINT UNSIGNED
)
BEGIN
    INSERT INTO UNI_FACULTADES (FACULTAD_ID, NOMBRE, ACTIVO)
    VALUES (p_facultad_id, p_nombre, p_activo);
END$$

CREATE PROCEDURE MODIFICAR_FACULTAD(
    IN p_facultad_id BIGINT UNSIGNED, IN p_nombre VARCHAR(100), IN p_activo TINYINT UNSIGNED
)
BEGIN
    UPDATE UNI_FACULTADES
    SET NOMBRE = p_nombre,
        ACTIVO = p_activo
    WHERE FACULTAD_ID = p_facultad_id;
END$$

CREATE PROCEDURE ELIMINAR_FACULTAD(
    IN p_id BIGINT UNSIGNED
)
BEGIN
    UPDATE UNI_FACULTADES SET ACTIVO = 0 WHERE FACULTAD_ID = p_id;
END$$

CREATE PROCEDURE OBTENER_FACULTAD_X_ID(
    IN p_id BIGINT UNSIGNED
)
BEGIN
    SELECT * FROM UNI_FACULTADES
    WHERE FACULTAD_ID = p_id;
END$$

CREATE PROCEDURE LISTAR_FACULTADS()
BEGIN
    SELECT * FROM UNI_FACULTADES WHERE ACTIVO = 1;
END$$

