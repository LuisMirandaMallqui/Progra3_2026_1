CREATE PROCEDURE EXISTE_CONFLICTO_HORARIO(
    IN p_matricula_id BIGINT UNSIGNED,
    IN p_horario_curso_id BIGINT UNSIGNED,
    OUT p_existe INT
)
BEGIN
    SELECT COUNT(*)
    INTO p_existe
    FROM UNI_MATRICULAS_HORARIOS mh
    INNER JOIN UNI_HORARIOS_CURSO_DET det_existente
        ON det_existente.HORARIO_CURSO_ID = mh.HORARIO_CURSO_ID
    INNER JOIN UNI_HORARIOS_CURSO_DET det_nuevo
        ON det_nuevo.HORARIO_CURSO_ID = p_horario_curso_id
       AND det_nuevo.DIA_SEMANA = det_existente.DIA_SEMANA
       AND det_nuevo.HORA_INICIO < det_existente.HORA_FIN
       AND det_nuevo.HORA_FIN > det_existente.HORA_INICIO
    WHERE mh.MATRICULA_ID = p_matricula_id;
END$$

CREATE PROCEDURE REGISTRAR_MATRICULA_HORARIO_VALIDADO(
    IN p_matricula_id BIGINT UNSIGNED,
    IN p_horario_curso_id BIGINT UNSIGNED,
    OUT p_resultado INT
)
BEGIN
    DECLARE v_cupo_maximo INT DEFAULT 0;
    DECLARE v_matriculados INT DEFAULT 0;
    DECLARE v_conflictos INT DEFAULT 0;
    DECLARE v_duplicado INT DEFAULT 0;

    SELECT COUNT(*)
    INTO v_duplicado
    FROM UNI_MATRICULAS_HORARIOS
    WHERE MATRICULA_ID = p_matricula_id
      AND HORARIO_CURSO_ID = p_horario_curso_id;

    IF v_duplicado > 0 THEN
        SET p_resultado = -1; -- Ya existe la matrícula en ese horario.
    ELSE
        SELECT CUPO_MAXIMO
        INTO v_cupo_maximo
        FROM UNI_HORARIOS_CURSO
        WHERE HORARIO_CURSO_ID = p_horario_curso_id;

        SELECT COUNT(*)
        INTO v_matriculados
        FROM UNI_MATRICULAS_HORARIOS
        WHERE HORARIO_CURSO_ID = p_horario_curso_id;

        IF v_matriculados >= v_cupo_maximo THEN
            SET p_resultado = -2; -- Cupo máximo alcanzado.
        ELSE
            CALL EXISTE_CONFLICTO_HORARIO(p_matricula_id, p_horario_curso_id, v_conflictos);

            IF v_conflictos > 0 THEN
                SET p_resultado = -3; -- Conflicto de horario.
            ELSE
                INSERT INTO UNI_MATRICULAS_HORARIOS (MATRICULA_ID, HORARIO_CURSO_ID, FECHA_REGISTRO)
                VALUES (p_matricula_id, p_horario_curso_id, CURRENT_TIMESTAMP);
                SET p_resultado = 1;
            END IF;
        END IF;
    END IF;
END$$

CREATE PROCEDURE CALCULAR_PROMEDIO_FINAL(
    IN p_matricula_id BIGINT UNSIGNED,
    IN p_horario_curso_id BIGINT UNSIGNED,
    OUT p_promedio DECIMAL(5,2)
)
BEGIN
    SELECT COALESCE(SUM(n.CALIFICACION * e.PESO / 100), 0)
    INTO p_promedio
    FROM UNI_NOTAS n
    INNER JOIN UNI_EVALUACIONES e ON e.EVALUACION_ID = n.EVALUACION_ID
    WHERE n.MATRICULA_ID = p_matricula_id
      AND n.HORARIO_CURSO_ID = p_horario_curso_id;
END$$

